"""The three focused documents in 00_PROJECT_DOCUMENTATION.

Kept in its own module so the long prose does not have to be escaped inside the
main generator. Called by `scripts/12_generate_project_docs.py`.

These are deliberately short and single-purpose: a reader who wants the project
in one page, the research gap on its own, or the objectives as a checklist,
should not have to read the full README to find them.
"""
from __future__ import annotations


def build_docs(a: dict) -> dict:
    build, cfg, ev, fs, eda = (a["build"], a["cfg"], a["ev"], a["fs"], a["eda"])
    s1 = build["step1_cohort"]
    f7 = build["step7_final"]
    m = (ev or {}).get("test_metrics", {})
    tm = (ev or {}).get("temporal_metrics", {})
    meta = (a["meta"] or {}).get("metadata", {})
    cv = fs["selection_inside_cv"]

    # ---------------------------------------------------------------- overview
    O = ["# Project Overview\n",
         "> Auto-generated by `scripts/12_generate_project_docs.py`.\n",
         "## In one paragraph\n",
         "When a bacterial culture turns positive, the organism is identified "
         "roughly 24 hours before the antimicrobial susceptibility test (AST) "
         "result arrives. This project builds an explainable machine-learning "
         "system that predicts, during that window, the probability that the "
         "laboratory will report the isolate **non-susceptible** to each of 54 "
         "antibiotics — then explains each prediction with SHAP, ranks the "
         "agents for clinician review behind cited clinical guardrails, and "
         "requires a recorded human decision. It is a research prototype and "
         "not an autonomous prescribing system.\n",
         "## The numbers\n", "| | |", "|---|--:|",
         f"| Source data | 5 linked de-identified tables, 1.7 GB, "
         f"{s1['n_rows_raw']:,} cohort rows |",
         f"| After cleaning | {f7['n_rows']:,} labelled rows |",
         f"| Cultures / patients | {f7['n_orders']:,} positive culture orders "
         f"from {f7['n_patients']:,} patients |",
         f"| Period | {s1['date_range'][0][:10]} to {s1['date_range'][1][:10]} |",
         f"| Antibiotics / organisms / specimens | 54 / "
         f"{s1['organism_clean_distinct']} / 3 |",
         f"| Target | non-susceptible (Resistant or Intermediate), "
         f"{100*f7['target_positive_rate']:.2f}% prevalence |",
         f"| Features | {fs['feature_inventory']['n_candidate_features']} "
         f"candidates reduced to {cfg['n_features']} |",
         f"| Final model | {meta.get('algorithm')} |"]
    if m:
        O += [f"| Held-out test performance | PR-AUC {m['pr_auc']}, ROC-AUC "
              f"{m['roc_auc']}, sensitivity {m['recall_sensitivity']}, "
              f"specificity {m['specificity']} |",
              f"| Temporal holdout | PR-AUC {tm.get('pr_auc')} |"]
    O += ["",
          "## What it does, end to end\n",
          "```text",
          "Raw data -> audit -> cleaning -> integration -> EDA ->",
          "feature engineering -> feature selection -> training ->",
          "evaluation -> SHAP -> ranking -> guardrails -> CLINICIAN DECIDES",
          "```\n",
          "Full diagram: "
          "[`../14_REPORT_MATERIAL/diagrams/methodology_workflow.png`]"
          "(../14_REPORT_MATERIAL/diagrams/methodology_workflow.png)\n",
          "## What makes it more than a notebook\n",
          "- **Raw data is never modified.** It is referenced in place, with an "
          "MD5 manifest and a verification script.",
          "- **Every published number is generated from a pipeline artefact**, "
          "so documentation cannot drift from the data. A consistency audit "
          "enforces it.",
          f"- **Leakage is demonstrated, not asserted** — including "
          f"{s1['organism_leaked_phenotype_rows']:,} rows where the resistance "
          "answer was hidden inside the organism *name*.",
          "- **The test partition is read exactly once.**",
          "- **Guardrails flag, never filter.** Nothing is hidden from the "
          "reviewing clinician.",
          "- **Dosage is relayed verbatim from the FDA label and never "
          "computed; cost is retrieved from CMS NADAC and never estimated.**\n",
          "## Safety\n",
          "> This application is a research/clinical decision-support "
          "prototype. It does not replace qualified healthcare professionals, "
          "antimicrobial susceptibility testing, clinical guidelines, or "
          "professional medical judgment. AI-generated predictions and "
          "recommendations must be reviewed by an appropriately qualified "
          "healthcare professional.\n",
          "## Where to look next\n", "| Question | Document |", "|---|---|",
          "| How do I run it? | [`../README.md`](../README.md) |",
          "| What is in the data? | "
          "[`../docs/DATA_DICTIONARY.md`](../docs/DATA_DICTIONARY.md) |",
          "| How was leakage handled? | "
          "[`../docs/DATA_LEAKAGE_ANALYSIS.md`](../docs/DATA_LEAKAGE_ANALYSIS.md) |",
          "| What does the data look like? | "
          "[`../02_DATA_ANALYSIS/EDA_REPORT.md`](../02_DATA_ANALYSIS/EDA_REPORT.md) |",
          "| How were features chosen? | "
          "[`../04_FEATURE_SELECTION/FEATURE_SELECTION_REPORT.md`]"
          "(../04_FEATURE_SELECTION/FEATURE_SELECTION_REPORT.md) |",
          "| How well does it work? | "
          "[`../docs/MODEL_EVALUATION.md`](../docs/MODEL_EVALUATION.md) |",
          "| What are its limits? | [`../MODEL_CARD.md`](../MODEL_CARD.md) |",
          "| Was it verified? | "
          "[`../docs/SYSTEM_VERIFICATION.md`](../docs/SYSTEM_VERIFICATION.md) |",
          "| State of every stage | "
          "[`../docs/PROJECT_STATUS.md`](../docs/PROJECT_STATUS.md) |", ""]

    # ------------------------------------------------------------ research gap
    mrsa_token = "`STAPH AUREUS {MRSA}`"
    G = ["# Research Gap\n",
         "> Auto-generated by `scripts/12_generate_project_docs.py`. Every "
         "claim below is backed by a measurement in this project.\n",
         "Published antimicrobial-resistance prediction work tends to share "
         "several methodological weaknesses. This project was built to address "
         "each one explicitly, and to show the evidence rather than assert the "
         "fix.\n",
         "## Gap 1 — Leakage is asserted, not demonstrated\n",
         "**Typical practice.** A sentence stating that leaky features were "
         "removed.\n",
         "**What this project does.** Every candidate pathway is investigated "
         "with measured evidence and the verdict published, including one a "
         "reader would not think to look for: the resistance phenotype written "
         f"into the organism *name*. {s1['organism_leaked_phenotype_rows']:,} "
         f"rows carry tokens such as {mrsa_token} or "
         "`KLEBSIELLA PNEUMONIAE (CARBAPENEM RESISTANT)`. Rows with a "
         "vancomycin-resistant token were **100%** resistant to glycopeptides "
         "against a 2.83% class baseline — the label, restated in text.\n",
         "Equally important, the most suspicious table was investigated and "
         "**cleared**: the prior-resistance history keys on the index culture "
         "order, but every event predates it by at least a day, it matches only "
         "4.13% of rows, and matched rows are 63.7% resistant rather than "
         "~100%. Predictive, and genuinely history.\n",
         "See [`../docs/DATA_LEAKAGE_ANALYSIS.md`]"
         "(../docs/DATA_LEAKAGE_ANALYSIS.md).\n",
         "## Gap 2 — Feature selection is a footnote\n",
         "**Typical practice.** Train on every column, or cite a single "
         "feature-importance plot.\n",
         f"**What this project does.** Seven methods, "
         f"{len(fs['candidate_sets'])} candidate feature sets compared on "
         "held-out validation patients, a feature-count sweep, an "
         "organism-blind ablation that quantifies how much of the signal the "
         "organism carries (PR-AUC 0.7615 falling to 0.6548), and — the part "
         "that is almost never done — a measurement of whether the selection "
         "*itself* leaked. Re-deriving the selection inside every "
         f"cross-validation fold scores {cv['nested_cv_pr_auc_mean']:.5f} "
         f"against {cv['global_cv_pr_auc_mean']:.5f} for the globally chosen "
         f"list: an optimism of "
         f"{cv['optimism_from_global_selection']:+.5f} PR-AUC, smaller than the "
         "fold-to-fold spread.\n",
         "A finding that would usually be buried: **no laboratory value and no "
         "age feature survived selection**, and the full-feature arm scores "
         "*worse* than the selected 30.\n",
         "See [`../04_FEATURE_SELECTION/FEATURE_SELECTION_REPORT.md`]"
         "(../04_FEATURE_SELECTION/FEATURE_SELECTION_REPORT.md).\n",
         "## Gap 3 — Random row splits inflate results\n",
         "**Typical practice.** `train_test_split` over rows.\n",
         "**What this project does.** 53.8% of patients contribute more than "
         "one culture order, and one contributes 175. A random row split would "
         "place the same patient — often the same organism, sometimes the same "
         "week — on both sides, so the test set would partly measure "
         "memorisation. All splits are grouped by patient, asserted by a test.\n",
         "A **temporal holdout** is reported alongside it, training on the "
         "earlier years and testing on the most recent, with patients "
         "straddling the cut-off removed from the test side. That is the "
         f"deployment-realistic number, and it is lower: PR-AUC "
         f"{tm.get('pr_auc')} against {m.get('pr_auc')}. It is reported rather "
         "than hidden.\n",
         "## Gap 4 — Explanation stops at a global bar chart\n",
         "**Typical practice.** One feature-importance figure.\n",
         "**What this project does.** Exact TreeSHAP, with additivity verified "
         "numerically. Per-prediction explanations are rendered in the "
         "application in clinical language. The model's **failures** are "
         "explained alongside its successes. And a mechanism check verifies "
         "that the history features move predictions in the clinically "
         "expected direction — the one feature whose SHAP direction disagreed "
         "was investigated and shown to be credit-splitting between collinear "
         "features rather than a learned shortcut.\n",
         "See [`../07_EXPLAINABLE_AI/XAI_REPORT.md`]"
         "(../07_EXPLAINABLE_AI/XAI_REPORT.md).\n",
         "## Gap 5 — Decision support that quietly becomes prescribing\n",
         "**Typical practice.** A ranked list presented as an answer.\n",
         "**What this project does.** The model's probability is never modified "
         "by any downstream layer. Clinical guardrails from cited sources "
         "(EUCAST/CLSI intrinsic resistance, FDA labelling for site "
         "suitability, WHO AWaRe stewardship tiers) **flag and re-order** "
         "options; they never delete one, so the clinician sees both what the "
         "model estimated and why an option was pushed down. Every option "
         "carries the number of training examples behind it. Dosage is quoted "
         "verbatim from the FDA label and never computed. The system has no "
         "mechanism to prescribe.\n",
         "## Gap 6 — Panel-selection bias is ignored\n",
         "**Typical practice.** Treat the AST panel as if it were complete.\n",
         "**What this project does.** The EDA measures it: only "
         f"{eda['antibiogram']['full_space_pct_with_any_test']}% of the "
         "organism x antibiotic space has any test at all. The model therefore "
         "learns the resistance pattern *conditional on being tested*, which is "
         "stated as a limitation in the model card rather than glossed over, "
         "and it is the reason a unified model that shares structure through "
         "antibiotic class and organism group was chosen over independent "
         "per-agent models.\n"]

    # -------------------------------------------------------------- objectives
    obj = [
        ("Audit the real datasets exhaustively before writing any model",
         a["audit"] is not None,
         "`docs/DATA_DICTIONARY.md` — all 5 files profiled column by column"),
        ("Establish the true relational structure and every leakage pathway",
         True,
         "`docs/DATA_RELATIONSHIPS.md`, `docs/DATA_LEAKAGE_ANALYSIS.md`"),
        ("Define the prediction task the data actually supports", True,
         "`docs/ML_PROBLEM_DEFINITION.md` — binary S vs non-S, with the "
         "3-class alternative trained and reported"),
        ("Understand the data before modelling it", eda is not None,
         "`02_DATA_ANALYSIS/EDA_REPORT.md` — 15-part EDA, 14 figures, "
         "21 tables"),
        ("Treat feature selection as a first-class experiment", fs is not None,
         f"7 methods, {len(fs['candidate_sets'])} candidate sets, and the "
         "leakage of the selection itself measured"),
        ("Compare model families and resolve class imbalance empirically",
         a["train"] is not None,
         "6 families compared; 4 imbalance strategies tested; SMOTE shown to "
         "harm performance"),
        ("Explain predictions individually as well as globally",
         a["xai"] is not None,
         "`07_EXPLAINABLE_AI/XAI_REPORT.md` — global, local, and failure cases"),
        ("Rank antibiotics for clinician review with cited guardrails, never "
         "as a prescription", True,
         "`08_RECOMMENDATION_ENGINE/` — EUCAST/CLSI, FDA labelling, WHO AWaRe"),
        ("Integrate only real, verified external services", True,
         "openFDA, RxNorm/RxNav, CMS NADAC verified live; the retired RxNav "
         "interaction API deliberately excluded"),
        ("Support a genomic module without fabricating genomic results",
         True,
         "`09_GENOMIC_AMR/` — implemented, INACTIVE, with a verified plug-in "
         "point"),
        ("Keep the clinician the decision-maker throughout", True,
         "Human-in-the-loop tab with a recorded Accept/Modify/Reject decision"),
        ("Make the whole project reproducible and verifiable", True,
         "`scripts/run_all.py` (21 stages), 111 tests, 59 verification checks, "
         "consistency audit"),
        ("Produce report-ready material", True,
         "`14_REPORT_MATERIAL/INDEX.md` — 8 diagrams, 44 figures, 41 tables"),
    ]
    B = ["# Objectives\n",
         "> Auto-generated by `scripts/12_generate_project_docs.py`. Status is "
         "derived from the artefact each objective produces.\n",
         "| # | Objective | Status | Evidence |", "|--:|---|---|---|"]
    for i, (text, done, evidence) in enumerate(obj, 1):
        B.append(f"| {i} | {text} | "
                 f"{'ACHIEVED' if done else 'OUTSTANDING'} | {evidence} |")
    B += ["",
          "## Explicit non-objectives\n",
          "These were considered and deliberately excluded, so that their "
          "absence is a decision rather than an omission:\n",
          "- **Autonomous prescribing.** The system has no mechanism to order a "
          "drug and must never be given one.",
          "- **Dose calculation.** Even with complete patient data this project "
          "would relay the label and leave the calculation to the prescriber. "
          "Creatinine clearance is not computed because the dataset has no "
          "body weight.",
          "- **Course-cost calculation.** It would require a dose the project "
          "does not generate.",
          "- **Genomic prediction.** These datasets contain no genomic data; "
          "the module is built and inactive rather than fabricated.",
          "- **Clinical outcome prediction.** The target is a laboratory "
          "susceptibility category, not cure or mortality.",
          "- **Drug-interaction checking.** The NLM API for it is retired; "
          "showing nothing is better than showing data from an unmaintained "
          "source.",
          "- **Paediatric use.** The youngest age band in the data is 18-24 "
          "years.\n"]

    return {"PROJECT_OVERVIEW.md": "\n".join(O),
            "RESEARCH_GAP.md": "\n".join(G),
            "OBJECTIVES.md": "\n".join(B)}
