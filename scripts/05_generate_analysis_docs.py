def leakage_doc(leak: dict, build: dict, rel: dict) -> str:
    s1 = build["step1_cohort"]
    s4 = build["step4_prior_med"]
    s5 = build["step5_prior_resistance"]
    s6 = build["step6_prior_culture_history"]
    m = leak["cohort_rows_matching_resistance_same_order_org_abx"]

    L = []
    L.append("# Data Leakage Analysis\n")
    L.append("> Auto-generated by `scripts/05_generate_analysis_docs.py` from "
             "`02_DATA_ANALYSIS/reports/leakage.json` and "
             "`01_DATA/processed/build_report.json`.\n")
    L.append("This is the single most important document in the project. In a medical "
             "prediction task, a model that reads any part of its own answer will look "
             "excellent offline and be useless — or dangerous — in practice.\n")

    L.append("## 1. The prediction moment\n")
    L.append("Leakage is only definable relative to a prediction time point, so the "
             "project fixes one explicitly:\n")
    L.append("> **T = the moment the organism identification is available for a positive "
             "culture, and before the antimicrobial susceptibility test (AST) result is "
             "reported.**\n")
    L.append("This is a real clinical gap. Organism identification (Gram stain, MALDI-TOF, "
             "rapid molecular panels) typically lands roughly 24 hours before the full AST "
             "panel. During that window the clinician must choose or continue therapy with "
             "the organism known and its susceptibility unknown. Everything the model is "
             "allowed to see must exist at T:\n")
    L.append("* patient demographics and the specimen/order context — known at collection;")
    L.append("* laboratory results from the 14 days before the culture — known;")
    L.append("* prior medications, prior cultures and prior resistance from earlier "
             "encounters — known;")
    L.append("* the identified organism — known at T by definition;")
    L.append("* **the susceptibility result itself, or anything derived from it — NOT "
             "known.**\n")

    L.append("## 2. Confirmed leakage found and removed\n")
    L.append("### 2.1 Resistance phenotype embedded in the organism name\n")
    L.append("The `organism` column is a laboratory dictionary dump, and some of its "
             "entries carry the answer in the text:\n")
    L.append("| Raw organism value | Rows |")
    L.append("|---|--:|")
    for k, v in list(s1["organism_leaked_phenotype_breakdown"].items()):
        L.append(f"| tokens matched: `{k}` | {n(v)} |")
    L.append(f"\nIn total **{n(s1['organism_leaked_phenotype_rows'])} rows** "
             f"({100*s1['organism_leaked_phenotype_rows']/s1['n_rows_clean']:.3f}% of the "
             "modelling rows) carry a resistance token such as "
             "`STAPH AUREUS {MRSA}`, `KLEBSIELLA PNEUMONIAE (CARBAPENEM RESISTANT)` or "
             "`ENTEROCOCCUS FAECIUM -  VANCO RESISTANT`.\n")
    if s1.get("organism_leak_evidence"):
        L.append("The tokens are demonstrably the label restated. Comparing the resistant "
                 "rate for rows carrying a token against the background rate for the same "
                 "antibiotic class:\n")
        L.append("| Token / antibiotic class | Rows with token | % Resistant with token | % Resistant, class baseline |")
        L.append("|---|--:|--:|--:|")
        for k, v in s1["organism_leak_evidence"].items():
            L.append(f"| `{k}` | {n(v['n_rows_with_token'])} | "
                     f"**{v['pct_resistant_when_token_present']}%** | "
                     f"{v['pct_resistant_overall_for_class']}% |")
        L.append("")
    L.append("**Action taken.** `src/preprocessing/organism_normalizer.py` strips every "
             "resistance token into a separate field, that field is dropped before "
             "modelling, and the cleaned species name is what the model sees. The "
             "morphotype tokens in the same column (`MUCOID`, `NON-MUCOID`, "
             "`COLONY VARIANT`) are *not* leakage — they are colony appearance observed at "
             "identification — so they are preserved as the feature "
             "`organism_morphotype`.\n")

    L.append("### 2.2 `was_positive`\n")
    L.append("Cross-tabulating `was_positive` against the target shows it is a "
             "deterministic restatement of whether a label exists at all:\n")
    L.append("| `was_positive` | Rows with a susceptibility result | Rows with no result |")
    L.append("|---|--:|--:|")
    for wp, counts in leak["was_positive_vs_target"].items():
        na = counts.get("<NA>", 0)
        labelled = sum(v for k, v in counts.items() if k != "<NA>")
        L.append(f"| `{wp}` | {n(labelled)} | {n(na)} |")
    L.append(f"\nEvery `was_positive = 0` row has no susceptibility result, and every "
             "labelled row has `was_positive = 1`. After the modelling cohort is filtered "
             f"to labelled rows the column is constant "
             f"(`{s1['was_positive_unique_after_filter']}`) — zero variance and, in "
             "principle, culture-result information. **Action taken: excluded.**\n")

    L.append("### 2.3 Same-day medication administrations\n")
    L.append(f"`medication_time_to_culturetime` reaches down to 0 days, and "
             f"**{n(s4['n_rows_same_day_t_eq_0'])} rows "
             f"({100*s4['n_rows_same_day_t_eq_0']/s4['n_rows_raw']:.2f}% of the prior "
             "medication file)** sit exactly at 0.\n")
    L.append(f"> {s4['same_day_exclusion_reason']}\n")
    L.append(f"**Action taken.** All `t == 0` rows are dropped "
             f"({n(s4['n_dropped_same_day'])} rows). Only `t >= 1` contributes to the "
             "prior-exposure features.\n")

    L.append("### 2.4 Identifiers\n")
    L.append("`anon_id`, `pat_enc_csn_id_coded` and `order_proc_id_coded` are arbitrary "
             "surrogate keys. They carry no clinical meaning, but they are highly "
             "predictive in a leaky way: a tree can memorise a patient key and recall that "
             "patient's outcome. **Action taken: all three are excluded from the feature "
             "matrix and retained only as split metadata** (`anon_id` groups the split, "
             "`order_proc_id_coded` links predictions back to a culture).\n")

    L.append("### 2.5 Redundant duplicate of the index culture time\n")
    L.append("`microbiology_cultures_microbial_resistance.order_time_jittered_utc` is "
             f"byte-identical to the cohort's order time for all "
             f"{n(leak['order_time_matches_between_cohort_and_resistance']['n_compared'])} "
             "orders compared. It is the *index* culture time repeated on every history "
             "row, not the time of the prior event. **Action taken: excluded as a duplicate "
             "column**; the prior event's timing is carried by "
             "`resistant_time_to_culturetime` instead.\n")

    L.append("## 3. Variables investigated and CLEARED\n")
    L.append("### 3.1 Prior resistance history — cleared, and it is the strongest signal\n")
    rt = leak["resistance_time_to_culture"]
    L.append("This table looked like the most dangerous candidate: it contains "
             "organism-antibiotic resistance events keyed on the *index* culture order. "
             "Three independent checks establish that it is history, not the answer.\n")
    L.append(f"1. **Timing.** `resistant_time_to_culturetime` has minimum "
             f"**{rt['min']}** day and **{n(rt['n_le_zero'])}** rows at or below zero "
             f"(median {rt['median']} days, 1st percentile {rt['quantiles']['0.01']} days). "
             "Every event predates the index culture by at least a day.")
    L.append(f"2. **Match rate.** Joining it to the cohort on "
             f"(order, organism, antibiotic) matches only {n(m['n_matched'])} of "
             f"{n(m['n_total'])} rows ({m['pct']}%). A leaked label would match nearly "
             "everything.")
    matched_r = m["target_breakdown_of_matched"].get("Resistant", 0)
    matched_tot = sum(v for k, v in m["target_breakdown_of_matched"].items()
                      if k in ("Resistant", "Susceptible", "Intermediate"))
    unm_r = m["target_breakdown_of_unmatched"].get("Resistant", 0)
    unm_tot = sum(v for k, v in m["target_breakdown_of_unmatched"].items()
                  if k in ("Resistant", "Susceptible", "Intermediate"))
    L.append(f"3. **Predictive but not deterministic.** Among matched rows "
             f"{100*matched_r/matched_tot:.1f}% are Resistant, versus "
             f"{100*unm_r/unm_tot:.1f}% among unmatched rows. That is a large, clinically "
             "plausible lift — a patient with documented prior resistance to this exact "
             "organism-drug pair is far more likely to be resistant again — but it is "
             "nowhere near the ~100% a leaked label would produce.\n")
    L.append("**Verdict: legitimate patient history. Included**, with every window "
             "restricted to `t >= 1` day.\n")

    L.append("### 3.2 Laboratory results — cleared\n")
    L.append(f"`Period_Day` is constant at "
             f"`{list(leak['labs_period_day_values'].keys())[0]}`, which documents that "
             "every lab aggregate summarises the **14 days before** the culture. The "
             "window closes at the culture, so no post-culture value can enter. "
             "**Verdict: included** (the constant column itself is dropped for zero "
             "variance).\n")

    L.append("### 3.3 Organism identity — cleared for the stated prediction moment\n")
    L.append("The organism is a culture result, so it would be leakage for a *pre-culture, "
             "empiric* task. Under the prediction moment defined in section 1 it is known "
             "by construction. To keep this honest rather than convenient, the feature "
             "selection experiments include an **organism-blind arm** that removes the "
             "organism entirely and reports how much performance depends on it "
             "(see `04_FEATURE_SELECTION/FEATURE_SELECTION_REPORT.md`).\n")

    L.append("### 3.4 Derived patient history — cleared by construction\n")
    L.append(f"> {s6['method']}\n")

    L.append("## 4. Leakage across the train/test split\n")
    ps = rel["patient_structure"]
    L.append(f"{ps['pct_patients_with_multiple_orders']}% of patients "
             f"({n(ps['patients_with_multiple_orders'])} of {n(ps['n_patients'])}) have "
             "more than one culture order, and one patient has "
             f"{n(ps['orders_per_patient_max'])}. Random row-level splitting would "
             "therefore put the same patient — often the same organism, sometimes the same "
             "week — on both sides, so the test set would partly measure memorisation.\n")
    L.append("**Action taken.** All splits are **grouped by `anon_id`**, so a patient "
             "appears in exactly one of train / validation / test. A **temporal holdout** "
             "is additionally reported as a deployment-realistic check "
             "(see `docs/ML_PROBLEM_DEFINITION.md` §5).\n")

    L.append("## 5. Summary — every exclusion and why\n")
    L.append("| Variable | Decision | Reason |")
    L.append("|---|---|---|")
    rows = [
        ("`anon_id`", "Exclude from features", "Patient identifier; memorisable. Retained only to group the split."),
        ("`pat_enc_csn_id_coded`", "Exclude", "Encounter identifier; no clinical content."),
        ("`order_proc_id_coded`", "Exclude from features", "Order identifier. Retained to link a prediction to its culture."),
        ("`was_positive`", "Exclude", "Culture result; constant (=1) after filtering to labelled rows — zero variance."),
        ("Resistance tokens inside `organism`", "Exclude", f"The label restated in text. {n(s1['organism_leaked_phenotype_rows'])} rows affected; stripped by the normaliser."),
        ("`resistance.order_time_jittered_utc`", "Exclude", "Byte-identical duplicate of the cohort order time."),
        ("`prior_med` rows with `t == 0`", "Exclude", f"{n(s4['n_rows_same_day_t_eq_0'])} same-day rows cannot be separated from empiric therapy started after collection."),
        ("`medication_category`", "Exclude", "Redundant 1:1 surrogate key for `medication_name`, and misleading as a class (CEF/CEF1 = cefazolin, CEF2 = ceftriaxone). A real class is derived from the name instead."),
        ("`Period_Day`", "Exclude", "Constant (14) — zero variance. Documents the lab window."),
        ("`susceptibility`, `severity`, `y_3class`", "Exclude from X", "These are the target."),
        ("`order_time_jittered_utc` (raw)", "Exclude", "Raw timestamp; replaced by year/month/day-of-week/hour features so the model cannot key on an exact instant."),
        ("`organism` (raw)", "Exclude", "Replaced by the cleaned `organism_clean` / `organism_genus` / `organism_group` fields."),
        ("`age` (raw string)", "Exclude", "Replaced by `age_band_ordinal` and `age_midpoint_years`."),
        ("Prior resistance features", "**Include**", "Verified strictly >= 1 day before the index culture; predictive but far from deterministic."),
        ("Prior medication features", "**Include**", "Restricted to `t >= 1` day before the culture."),
        ("Lab aggregates (14-day window)", "**Include**", "Window closes at the culture."),
        ("Derived prior-culture history", "**Include**", "Cumulative sums shifted to exclude the current order."),
        ("`organism_clean` / genus / group", "**Include**", "Known at the stated prediction moment. An organism-blind ablation is reported."),
    ]
    for a, b, c in rows:
        L.append(f"| {a} | {b} | {c} |")
    L.append("")
    return "\n".join(L)


