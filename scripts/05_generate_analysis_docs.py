def problem_doc(build: dict, leak: dict, rel: dict) -> str:
    s1 = build["step1_cohort"]
    f = build["step7_final"]
    ps = rel["patient_structure"]
    td = leak["target_distribution"]
    L = []
    L.append("# ML Problem Definition\n")
    L.append("> Auto-generated by `scripts/05_generate_analysis_docs.py`.\n")

    L.append("## 1. What the data can actually support\n")
    L.append("The label column is `susceptibility` in "
             "`microbiology_cultures_cohort.csv`. Its full observed distribution:\n")
    L.append("| Value | Rows | Share of labelled rows |")
    L.append("|---|--:|--:|")
    tot = sum(v for k, v in td.items() if k != "nan")
    for k, v in td.items():
        if k == "nan":
            continue
        L.append(f"| `{k}` | {n(v)} | {100*v/tot:.3f}% |")
    L.append(f"| *(no result — negative culture)* | {n(td['nan'])} | — |")
    L.append("")
    L.append("Two of the five categories are not susceptibility phenotypes: "
             f"`Inconclusive` ({n(td['Inconclusive'])} rows) is an uninterpretable test and "
             f"`Synergism` ({n(td['Synergism'])} rows) reports a two-drug interaction "
             "assay, not the single-agent phenotype the rest of the column encodes. Both "
             "are removed rather than forced into a class they do not belong to "
             f"({n(s1['n_dropped_non_phenotype_result'])} rows).\n")

    L.append("## 2. Chosen task\n")
    L.append("**Primary task — binary classification: Susceptible vs Non-susceptible.**\n")
    L.append("`Intermediate` is grouped with `Resistant` into a single *non-susceptible* "
             "class. This is the standard antimicrobial-stewardship reading: an "
             "Intermediate result means the agent cannot be relied on at ordinary dosing, "
             "so for the decision the model supports — *is this agent a defensible option?* "
             "— Intermediate and Resistant carry the same clinical consequence. Collapsing "
             "them also avoids modelling a 2.98% class that is defined by a narrow MIC "
             "band around a breakpoint and is the least reproducible category in AST.\n")
    tb = s1["target_binary_distribution"]
    L.append("| Class | Rows | Share |")
    L.append("|---|--:|--:|")
    L.append(f"| Susceptible (0) | {n(tb['susceptible'])} | "
             f"{100*tb['susceptible']/s1['n_rows_clean']:.3f}% |")
    L.append(f"| Non-susceptible (1) = Resistant + Intermediate | {n(tb['non_susceptible'])} | "
             f"{100*tb['non_susceptible']/s1['n_rows_clean']:.3f}% |")
    L.append("")
    L.append(f"Positive-class prevalence is **{100*s1['target_binary_positive_rate']:.2f}%** "
             "— imbalanced, but not extremely so. Handling is documented in "
             "`docs/MODEL_EVALUATION.md`.\n")
    L.append("**Secondary task — 3-class Susceptible / Intermediate / Resistant.** The data "
             f"does support it ({n(s1['target_3class_distribution'].get('Intermediate', 0))} "
             "Intermediate rows), so it is trained and reported as a secondary analysis to "
             "show what is lost and gained by keeping the middle category, rather than "
             "being asserted as impossible.\n")

    L.append("## 3. Unit of analysis\n")
    L.append(f"One row = **one (culture order x organism x antibiotic tested)** "
             f"combination. The final table holds {n(f['n_rows'])} such rows, drawn from "
             f"{n(f['n_orders'])} positive culture orders and {n(f['n_patients'])} "
             "patients.\n")
    L.append("A single culture order contributes one row per antibiotic on its AST panel "
             f"(mean {f['n_rows']/f['n_orders']:.1f} rows per order). Which agents appear "
             "on the panel is decided by the laboratory, not at random — a structural "
             "feature of the data that Section 4 addresses directly.\n")

    L.append("## 4. Model architecture: three candidate framings, compared\n")
    L.append("| Approach | How it works | Why it was or was not chosen |")
    L.append("|---|---|---|")
    L.append("| **A. One model per antibiotic** | Train 54 independent classifiers, one "
             "per agent. | Rejected as the primary design. The panel is extremely ragged: "
             "Ciprofloxacin has 111,321 rows while Cefpodoxime has 9 and Chloramphenicol "
             "12. Two thirds of the agents cannot support an independent model, and "
             "nothing is shared between them, so a rare carbapenem cannot borrow from a "
             "common one. Retained as a **comparison arm** for the highest-volume agents. |")
    L.append("| **B. Multi-output / multi-label** | One model predicting all 54 agents per "
             "isolate simultaneously. | Rejected. The label matrix would be ~76% missing "
             "by construction, because each isolate is only tested against the panel the "
             "laboratory selected. Multi-output learners require a dense target; the "
             "missingness here is informative (panel choice depends on organism and "
             "specimen), so masking it would bias the model. |")
    L.append("| **C. Unified model, antibiotic as a feature** | One model over "
             "(isolate, antibiotic) rows, with the agent and its class as input features. "
             "| **Chosen.** It matches the natural grain of the data, uses every row, "
             "shares structure across agents in the same class, and — decisively for the "
             "application — it can score *any* agent for a new isolate, which is what a "
             "ranked recommendation needs. |")
    L.append("")
    L.append("The chosen design is made possible by the antibiotic taxonomy in "
             "`src/preprocessing/antibiotic_taxonomy.py`, which gives every one of the 54 "
             "agents a class, subclass and WHO AWaRe category so that rare agents inherit "
             "structure from their class.\n")

    L.append("## 5. Splitting protocol\n")
    L.append(f"**Primary: grouped by patient.** {ps['pct_patients_with_multiple_orders']}% "
             "of patients have more than one culture order, so the split is grouped on "
             "`anon_id` (train / validation / test = 70 / 10 / 20 by patient). No patient "
             "appears in more than one partition. Cross-validation inside training uses "
             "`StratifiedGroupKFold` on the same key.\n")
    L.append("**Secondary: temporal holdout.** The cohort spans "
             f"{s1['date_range'][0][:10]} to {s1['date_range'][1][:10]}. Resistance "
             "prevalence and prescribing both drift over that period, so a second "
             "evaluation trains on the earlier years and tests on the most recent ones. "
             "This measures the thing that actually matters for deployment — whether a "
             "model fitted on the past still works on the future — and is reported "
             "alongside the grouped result rather than instead of it.\n")

    L.append("## 6. Metrics\n")
    L.append("Accuracy is reported but is **not** the selection metric: predicting "
             f"\"susceptible\" for every row would already score "
             f"{100*(1-s1['target_binary_positive_rate']):.1f}%. Model selection uses:\n")
    L.append("| Metric | Why it matters here |")
    L.append("|---|---|")
    L.append("| **PR-AUC (average precision)** | Primary selection metric. The positive "
             "class (non-susceptible) is the minority and the clinically costly one; PR-AUC "
             "is the metric that responds to it. |")
    L.append("| **ROC-AUC** | Threshold-free ranking quality; comparable to the published "
             "AMR-prediction literature. |")
    L.append("| **Recall / sensitivity for non-susceptible** | A missed resistance is an "
             "ineffective antibiotic given to a patient — the expensive error. |")
    L.append("| **Specificity** | A false resistance call pushes the clinician towards an "
             "unnecessarily broad agent, which drives future resistance. |")
    L.append("| **Precision, F1, macro-F1, weighted-F1** | Reported for completeness and "
             "for the 3-class secondary task. |")
    L.append("| **Calibration (Brier score, reliability curve)** | The application shows "
             "probabilities to a clinician and ranks agents by them. A miscalibrated 0.8 "
             "is actively misleading, so calibration is treated as a first-class result, "
             "not an afterthought. |")
    L.append("")

    L.append("## 7. What this model is not\n")
    L.append("It estimates the probability that a *laboratory* would call an isolate "
             "non-susceptible to an agent. It does not predict clinical cure, it does not "
             "account for the site of infection beyond the specimen type, source control, "
             "drug penetration, allergy, renal or hepatic dosing, pregnancy, interactions "
             "or cost-effectiveness, and it cannot replace an actual AST. Every use of its "
             "output in this project is framed as decision support for a qualified "
             "clinician who remains the decision-maker.\n")
    return "\n".join(L)


