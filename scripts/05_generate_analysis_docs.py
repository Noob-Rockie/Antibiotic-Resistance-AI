def relationships_doc(rel: dict, build: dict) -> str:
    grains = {g["table"]: g for g in rel["grains"]}
    rels = {(r["left"], r["right"]): r for r in rel["relationships"]}
    ps = rel["patient_structure"]
    L = []
    L.append("# Dataset Relationships\n")
    L.append("> Auto-generated by `scripts/05_generate_analysis_docs.py`. "
             "Every number is measured, not assumed.\n")
    L.append("![Dataset relationships](diagrams/dataset_relationships.png)\n")

    L.append("## 1. The identifier hierarchy\n")
    L.append("All five files share the same three identifier columns:\n")
    L.append("| Column | Level | Distinct values | Notes |")
    L.append("|---|---|--:|---|")
    L.append(f"| `anon_id` | Patient | {n(ps['n_patients'])} | De-identified patient key. "
             f"{ps['pct_patients_with_multiple_orders']}% of patients have more than one "
             f"culture order (max {n(ps['orders_per_patient_max'])}). |")
    L.append(f"| `pat_enc_csn_id_coded` | Encounter | {n(ps['n_encounters'])} | "
             f"{ps['orders_per_encounter_mean']} culture orders per encounter on average. |")
    L.append(f"| `order_proc_id_coded` | Culture order | {n(ps['n_culture_orders'])} | "
             "**The single join key used by the whole pipeline.** |")
    L.append("")
    L.append("`order_proc_id_coded` is nested strictly inside encounter, which is nested "
             "inside patient, so the triple `(anon_id, pat_enc_csn_id_coded, "
             "order_proc_id_coded)` and `order_proc_id_coded` alone identify exactly the "
             "same set of culture orders. The pipeline therefore joins on the single "
             "column and carries `anon_id` only as split metadata.\n")
    L.append("**Consequence for evaluation.** Because 53.8% of patients contribute more "
             "than one culture order, a naive random row split would place the same "
             "patient on both sides of the split and inflate every metric. All splits in "
             "this project are grouped by `anon_id`. See `docs/ML_PROBLEM_DEFINITION.md`.\n")

    L.append("## 2. Table grain (primary key), measured\n")
    L.append("| Table | Rows | Smallest unique key found | Rows per `order_proc_id_coded` |")
    L.append("|---|--:|---|--:|")
    grain_desc = {
        "cohort": ("`order_proc_id_coded` + `organism` + `antibiotic`", 2),
        "demographics": ("`order_proc_id_coded` (true primary key)", 1),
        "labs": ("no unique key — see leakage/quality notes", 1),
        "resistance": ("`order` + `organism` + `antibiotic` + `resistant_time_to_culturetime`", 0),
        "prior_med": ("no unique key — 40.3% exact duplicate rows", 0),
    }
    for t, g in grains.items():
        cg = g["candidate_grains"]
        per_order = next((c["avg_rows_per_key"] for c in cg
                          if c["columns"] == ["order_proc_id_coded"]), None)
        L.append(f"| `{t}` | {n(g['n_rows'])} | {grain_desc.get(t, ('—', 0))[0]} | "
                 f"{per_order if per_order else '—'} |")
    L.append("")
    L.append("Full candidate-key evidence:\n")
    for t, g in grains.items():
        L.append(f"**`{t}`** ({n(g['n_rows'])} rows)\n")
        L.append("| Candidate key | Distinct combinations | Unique key? | Avg rows per key |")
        L.append("|---|--:|:-:|--:|")
        for c in g["candidate_grains"]:
            L.append(f"| {' + '.join(f'`{x}`' for x in c['columns'])} | "
                     f"{n(c['n_unique'])} | {'YES' if c['is_unique_key'] else 'no'} | "
                     f"{c['avg_rows_per_key']} |")
        L.append("")

    L.append("## 3. Relationship cardinality and coverage\n")
    L.append("Measured by comparing key sets — no merge was executed to obtain these "
             "numbers.\n")
    L.append("| From | To | Cardinality | Cohort orders matched | Max rows per key on the right |")
    L.append("|---|---|:-:|--:|--:|")
    for (a, b), r in rels.items():
        L.append(f"| `{a}` | `{b}` | {r['cardinality']} | "
                 f"{n(r['n_keys_in_both'])} ({r['pct_left_keys_matched']}%) | "
                 f"{n(r['right_max_rows_per_key'])} |")
    L.append("")
    L.append("Reading of the table:\n")
    L.append("* **demographics** is the only genuine 1:1 companion — every one of the "
             f"{n(ps['n_culture_orders'])} culture orders has exactly one demographics row, "
             "and there are no orphans in either direction. It is safe to join directly.")
    L.append("* **labs**, **resistance** and **prior_med** are all one-to-many against the "
             "culture order. Joining any of them directly onto the cohort would multiply "
             "the label rows — up to 483x for `resistance` and 748x for `prior_med`. Each "
             "is therefore **aggregated to one row per key before it is joined**, never "
             "joined raw.")
    L.append("* Coverage is partial and is modelled explicitly: only "
             f"{rels[('cohort','labs')]['pct_left_keys_matched']}% of orders have any lab "
             f"result, {rels[('cohort','prior_med')]['pct_left_keys_matched']}% have prior "
             f"medication history and {rels[('cohort','resistance')]['pct_left_keys_matched']}% "
             "have prior resistance history. Rather than imputing a fictitious history, the "
             "pipeline adds explicit `has_labs`, `has_prior_med_history` and "
             "`has_prior_resistance_history` indicators and fills count features with 0 "
             "(a true zero: no recorded prior event).")
    L.append("")

    L.append("## 4. Join protocol enforced in code\n")
    L.append("`scripts/04_build_analytic_dataset.py` routes every merge through "
             "`validated_merge()`, which refuses to run unless the join is provably safe:\n")
    L.append("```python")
    L.append("def validated_merge(left, right, on, how, name, expect_right_unique=True):")
    L.append("    # 1. right side must be unique on the join keys, else refuse")
    L.append("    # 2. count how many left rows actually match")
    L.append("    # 3. execute the merge")
    L.append("    # 4. assert the row count did not change; raise if it did")
    L.append("```")
    L.append("Any fan-out or row loss raises an exception rather than silently corrupting "
             "the dataset. The recorded result of every join in the build:\n")
    if build.get("step7_joins"):
        L.append("| Join | Keys | Rows before | Rows after | Right side unique? | Left rows matched |")
        L.append("|---|---|--:|--:|:-:|--:|")
        for j in build["step7_joins"]:
            L.append(f"| `{j['join']}` | {' + '.join(f'`{k}`' for k in j['keys'])} | "
                     f"{n(j['rows_before'])} | {n(j['rows_after'])} | "
                     f"{'YES' if j['right_side_unique_on_keys'] else 'NO'} | "
                     f"{n(j['left_rows_matched'])} ({j['pct_left_rows_matched']}%) |")
        L.append("")
    return "\n".join(L)


