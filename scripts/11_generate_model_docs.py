def xai_doc(xai, ev) -> str:
    L = []
    L.append("# Explainable AI Report\n")
    L.append("> Auto-generated by `scripts/11_generate_model_docs.py` from "
             "`07_EXPLAINABLE_AI/xai_report.json`.\n")
    g = xai["global"]
    L.append("## 1. Method\n")
    L.append("`shap.TreeExplainer` computes exact Shapley values for the "
             "deployed gradient-boosted model, so no sampling approximation is "
             "involved. Three properties make it the right choice here:\n")
    L.append("- **Local faithfulness** — a clinician needs to know why *this* "
             "isolate got *this* number, which split-gain importance cannot "
             "answer.")
    L.append("- **Additivity** — the contributions for one prediction sum "
             "exactly to the gap between that prediction and the model's base "
             "rate, which makes an explanation auditable.")
    L.append("- **Consistency** — if the model changes so a feature matters "
             "more, its attribution cannot fall. Impurity importance offers no "
             "such guarantee.\n")
    L.append(f"Base value (model log-odds at the population rate): "
             f"**{g['base_value_log_odds']}**. "
             f"{n(g['n_rows_explained'])} held-out test rows explained.\n")
    L.append("**What SHAP does not give.** A SHAP value attributes the MODEL's "
             "output, not causation in the patient. \"Prior fluoroquinolone "
             "exposure raised the predicted resistance\" means the estimate "
             "moved; it does not establish that the exposure caused the "
             "resistance. Every user-facing string in the application is worded "
             "accordingly.\n")

    L.append("## 2. Global feature importance\n")
    L.append("| Rank | Feature | mean(\\|SHAP\\|) |")
    L.append("|--:|---|--:|")
    for i, (k, v) in enumerate(list(g["mean_abs_shap"].items())[:25], 1):
        L.append(f"| {i} | `{k}` | {v} |")
    L.append("\n![Global SHAP](../07_EXPLAINABLE_AI/figures/01_shap_global_bar.png)\n")
    L.append("![SHAP beeswarm](../07_EXPLAINABLE_AI/figures/02_shap_summary_beeswarm.png)\n")
    L.append("The beeswarm plot is the more informative of the two: it shows "
             "direction as well as magnitude, so a feature whose high values "
             "push towards resistance is visibly distinguishable from one whose "
             "high values push the other way.\n")

    L.append("## 3. Do the history features behave the way clinicians expect?\n")
    dc = xai.get("direction_checks", {})
    L.append(f"> {dc.get('interpretation', '')}\n")
    if dc.get("correlations"):
        L.append("| Feature | corr(value, SHAP) | Expected | n | Verdict |")
        L.append("|---|--:|:-:|--:|---|")
        contradictions = []
        for f, v in dc["correlations"].items():
            corr = v["corr_value_vs_shap"]
            ok = v["shap_sign_as_expected"]
            if not ok:
                contradictions.append((f, v))
            L.append(f"| `{f}` | {corr:+.4f} | {v['expected_sign']} | "
                     f"{n(v['n'])} | "
                     f"{'as expected' if ok else '**contradicts — investigated below**'} |")
        L.append("\nThis is a mechanism check, not a performance metric. A model "
                 "can score well while having learned a shortcut, so the "
                 "direction of the strongest history features is verified "
                 "rather than assumed.\n")
        if dc.get("how_to_read_a_contradiction"):
            L.append(f"> {dc['how_to_read_a_contradiction']}\n")
        for f, v in contradictions:
            raw = v.get("raw_marginal_association")
            L.append(f"### Investigating `{f}`\n")
            if raw:
                inverted = (raw["outcome_rate_when_feature_gt_0"]
                            <= raw["outcome_rate_when_feature_eq_0"])
                L.append("**Raw marginal association (model-independent):**\n")
                L.append("| | Value |")
                L.append("|---|--:|")
                L.append(f"| Non-susceptibility rate when the feature is 0 | "
                         f"{raw['outcome_rate_when_feature_eq_0']:.4f} |")
                L.append(f"| Non-susceptibility rate when the feature is > 0 | "
                         f"{raw['outcome_rate_when_feature_gt_0']:.4f} |")
                L.append(f"| Mean value among non-susceptible rows | "
                         f"{raw['mean_value_when_nonsusceptible']:.4f} |")
                L.append(f"| Mean value among susceptible rows | "
                         f"{raw['mean_value_when_susceptible']:.4f} |")
                L.append("")
                if inverted:
                    L.append("The raw association is **also inverted**. This is "
                             "the serious case: the feature does not behave the "
                             "way the clinical reasoning says it should, and it "
                             "should be investigated before any deployment.\n")
                else:
                    L.append("The raw association is in the **clinically "
                             "expected direction** — the feature on its own "
                             "predicts more resistance, by a wide margin. So "
                             "the model has not learned an inverted "
                             "relationship.\n")
            partners = v.get("correlated_selected_features_abs_gt_0.5", {})
            if partners:
                L.append("**Correlated partners in the selected feature set:**\n")
                L.append("| Partner feature | Pearson r |")
                L.append("|---|--:|")
                for k, c in partners.items():
                    L.append(f"| `{k}` | {c:+.4f} |")
                L.append("")
                L.append("These partners carry the same clinical signal and all "
                         "receive strongly positive SHAP attributions. Once "
                         "they are in the model, the residual role of this "
                         "feature is a **correction** rather than the primary "
                         "signal, and SHAP assigns it a compensating negative "
                         "contribution. This is credit-splitting between "
                         "collinear features — expected behaviour, not a "
                         "defect.\n")
                L.append("The practical consequence, and it is a real "
                         "limitation: **an individual SHAP attribution for one "
                         "member of a correlated group should not be read in "
                         "isolation.** The application therefore shows the top "
                         "contributions together rather than quoting a single "
                         "one, and the correlation filter (|rho| > 0.95) was "
                         "deliberately not tightened further, because removing "
                         "one of each moderately-correlated pair would have "
                         "cost predictive performance to buy tidier "
                         "attributions.\n")

    L.append("## 4. Individual prediction explanations\n")
    L.append("Five cases were drawn from the held-out test partition — two the "
             "model got confidently right, two it got wrong, and one on the "
             "decision boundary. The failures are included deliberately: an "
             "explanation method is only useful if it also explains mistakes.\n")
    for label, e in xai.get("local_explanations", {}).items():
        L.append(f"### {label.replace('_', ' ').title()}\n")
        L.append(f"**{e['organism']}** · {e['antibiotic']} · {e['specimen']}  \n")
        L.append(f"Model P(non-susceptible) = **{e['p_nonsusceptible']}**; "
                 f"the laboratory reported "
                 f"**{'non-susceptible' if e['actual_nonsusceptible'] else 'susceptible'}**.\n")
        L.append("| Feature | Encoded value | SHAP contribution | Direction |")
        L.append("|---|--:|--:|---|")
        for c in e["top_contributions"][:8]:
            L.append(f"| `{c['feature']}` | {c['value']} | {c['shap']:+.4f} | "
                     f"{c['direction']} |")
        L.append(f"\nBase value {e['base_value_log_odds']:.4f} + contributions "
                 f"{e['sum_of_contributions']:+.4f} = model output "
                 f"{e['prediction_log_odds']:.4f} (log-odds).\n")
        L.append(f"![{label}](../07_EXPLAINABLE_AI/figures/04_local_{label}.png)\n")

    bc = xai.get("by_antibiotic_class")
    if bc:
        L.append("## 5. What drives the prediction, by antibiotic class\n")
        L.append("The same model uses different evidence for different classes "
                 "— which is exactly what a unified model with the antibiotic "
                 "as a feature is supposed to do.\n")
        L.append("| Antibiotic class | Test rows | Top 5 features by mean\\|SHAP\\| |")
        L.append("|---|--:|---|")
        for cls, d in sorted(bc.items(), key=lambda kv: -kv[1]["n_rows"]):
            top = ", ".join(f"`{k}`" for k in list(d["top_5"])[:5])
            L.append(f"| {cls} | {n(d['n_rows'])} | {top} |")
        L.append("")

    L.append("## 6. How this reaches the clinician\n")
    L.append("The application's *Explanation* tab runs the same "
             "`src/explainability/shap_explainer.py` code on the live "
             "prediction and renders the top contributions in clinical "
             "language, so what selected a feature, what the report documents "
             "and what the clinician sees are all the same computation.\n")
    return "\n".join(L)


