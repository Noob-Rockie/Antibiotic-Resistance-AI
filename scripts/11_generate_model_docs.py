def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def n(x):
    return f"{x:,}" if isinstance(x, int) else str(x)


def pct(x):
    return f"{100 * float(x):.2f}%"


# ===========================================================================
def evaluation_doc(ev, train, cfg, build) -> str:
    m = ev["test_metrics"]
    L = []
    L.append("# Model Evaluation\n")
    L.append("> Auto-generated by `scripts/11_generate_model_docs.py` from "
             "`06_MODEL_EVALUATION/evaluation_report.json` and "
             "`05_MODEL_TRAINING/experiments/training_report.json`.\n")
    L.append("> The test partition was read exactly once, by "
             "`scripts/08_evaluate_models.py`. Nothing in feature selection, "
             "model selection, tuning or calibration touched it.\n")

    # ---- 1. splits ---------------------------------------------------------
    L.append("## 1. Data partitions\n")
    L.append("| Partition | Rows | Patients | Culture orders | Non-susceptible rate | Date range |")
    L.append("|---|--:|--:|--:|--:|---|")
    for part in ("train", "val", "test"):
        p = ev["split"]["partitions"].get(part)
        if not p:
            continue
        L.append(f"| {part} | {n(p['n_rows'])} | {n(p['n_patients'])} | "
                 f"{n(p['n_orders'])} | {pct(p['positive_rate'])} | "
                 f"{p['date_min'][:10]} → {p['date_max'][:10]} |")
    L.append("\nSplits are grouped on `anon_id`, so no patient appears in more "
             "than one partition. The near-identical positive rates across "
             "partitions confirm the grouped split did not distort the class "
             "balance.\n")

    # ---- 2. model comparison ----------------------------------------------
    L.append("## 2. Model family comparison\n")
    L.append("All six families were fitted on identical training rows with the "
             "identical 30-feature set and scored on the identical validation "
             "patients.\n")
    L.append("| Model | Accuracy | Precision | Recall | F1 | ROC-AUC | **PR-AUC** | Specificity | Brier | Training time (s) |")
    L.append("|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|")
    best = max(train["model_comparison"], key=lambda r: r["pr_auc"])
    for r in sorted(train["model_comparison"], key=lambda r: -r["pr_auc"]):
        b = "**" if r["model"] == best["model"] else ""
        L.append(f"| {b}{r['model']}{b} | {r['accuracy']:.4f} | "
                 f"{r['precision']:.4f} | {r['recall_sensitivity']:.4f} | "
                 f"{r['f1']:.4f} | {r['roc_auc']:.4f} | "
                 f"{b}{r['pr_auc']:.4f}{b} | {r['specificity']:.4f} | "
                 f"{r['brier']:.4f} | {r['train_seconds']:.0f} |")
    L.append("")
    L.append("Why each family was included:\n")
    for r in train["model_comparison"]:
        L.append(f"- **{r['model']}** — {r.get('rationale', '')}")
    L.append("")
    lr = next((r for r in train["model_comparison"]
               if r["model"] == "LogisticRegression"), None)
    if lr:
        L.append(f"The gap between the linear baseline "
                 f"(PR-AUC {lr['pr_auc']:.4f}) and the boosted trees "
                 f"({best['pr_auc']:.4f}) is the clearest single result in the "
                 "comparison: roughly a quarter of the achievable signal lives "
                 "in interactions between the antibiotic, the organism and the "
                 "patient's history, and an additive model cannot reach it.\n")

    # ---- 3. imbalance ------------------------------------------------------
    L.append("## 3. Class imbalance — resolved by experiment, not by reflex\n")
    imb = train["imbalance"]
    L.append(f"Positive-class prevalence is **{pct(imb['positive_rate'])}**. "
             f"Four strategies were compared on identical validation patients.\n")
    L.append("| Strategy | Training rows | **PR-AUC** | ROC-AUC | Recall | Precision | F1 | Brier |")
    L.append("|---|--:|--:|--:|--:|--:|--:|--:|")
    for r in sorted(imb["results"], key=lambda r: -r["pr_auc"]):
        b = "**" if r["strategy"] == imb["selected"] else ""
        L.append(f"| {b}{r['strategy']}{b} | {n(r['n_train_rows'])} | "
                 f"{b}{r['pr_auc']:.4f}{b} | {r['roc_auc']:.4f} | "
                 f"{r['recall_sensitivity']:.4f} | {r['precision']:.4f} | "
                 f"{r['f1']:.4f} | {r['brier']:.4f} |")
    L.append(f"\n**Selected: {imb['selected']}.**\n")
    L.append(f"> {imb['rationale']}\n")
    base = next(r for r in imb["results"] if r["strategy"] == "none (baseline)")
    spw = next((r for r in imb["results"]
                if r["strategy"] == "scale_pos_weight"), None)
    smote = next((r for r in imb["results"]
                  if r["strategy"].startswith("SMOTE")), None)
    L.append("Three things the table settles:\n")
    if smote:
        L.append(f"1. **SMOTE actively harms this problem** — PR-AUC "
                 f"{smote['pr_auc']:.4f} against {base['pr_auc']:.4f} for doing "
                 f"nothing, a {100*(smote['pr_auc']-base['pr_auc'])/base['pr_auc']:.1f}% "
                 "loss. Interpolating between ordinal-coded organism and "
                 "antibiotic codes manufactures entities that do not exist, and "
                 "interpolating sparse prior-exposure counts invents patient "
                 "histories. This is the empirical version of the argument "
                 "against applying SMOTE by reflex.")
    if spw:
        L.append(f"2. **Re-weighting trades calibration for recall.** "
                 f"`scale_pos_weight` raises recall from "
                 f"{base['recall_sensitivity']:.4f} to "
                 f"{spw['recall_sensitivity']:.4f} at a fixed 0.5 threshold, "
                 f"but Brier worsens from {base['brier']:.4f} to "
                 f"{spw['brier']:.4f} and PR-AUC is unchanged within noise. It "
                 "moves the operating point; it does not add information.")
    L.append("3. **The right answer was to leave the class distribution alone "
             "and move the threshold instead.** Ranking quality (PR-AUC, "
             "ROC-AUC) is what the application needs, because it shows "
             "calibrated probabilities and an ordering rather than a binary "
             "verdict. Section 6 reports the operating points.\n")

    # ---- 4. tuning ---------------------------------------------------------
    L.append("## 4. Hyperparameter tuning\n")
    L.append("`RandomizedSearchCV`, 12 candidates, 3-fold "
             "`StratifiedGroupKFold` grouped on `anon_id`, scored by average "
             "precision.\n")
    L.append("| Model | Best CV PR-AUC | Validation PR-AUC | Search time (s) |")
    L.append("|---|--:|--:|--:|")
    for name, t in train["tuning"].items():
        L.append(f"| {name} | {t['best_cv_pr_auc']:.5f} | "
                 f"{t['validation_metrics']['pr_auc']:.5f} | "
                 f"{t['search_seconds']:.0f} |")
    L.append("")
    for name, t in train["tuning"].items():
        L.append(f"**{name} best parameters**\n")
        L.append("```json")
        L.append(json.dumps(t["best_params"], indent=2))
        L.append("```\n")

    # ---- 5. headline -------------------------------------------------------
    L.append("## 5. Final model on the held-out test partition\n")
    L.append(f"Algorithm: **{train['tuning'] and max(train['tuning'].items(), key=lambda kv: kv[1]['validation_metrics']['pr_auc'])[0]}** · "
             f"{cfg['n_features']} features · "
             f"{n(ev['split']['partitions']['test']['n_rows'])} test rows from "
             f"{n(ev['split']['partitions']['test']['n_patients'])} unseen "
             "patients.\n")
    L.append("| Metric | Value | Reading |")
    L.append("|---|--:|---|")
    rows = [
        ("PR-AUC", m["pr_auc"],
         f"No-skill baseline is the prevalence, {m['positive_rate']:.4f}. "
         f"95% CI {m.get('pr_auc_ci95')}."),
        ("ROC-AUC", m["roc_auc"], f"95% CI {m.get('roc_auc_ci95')}."),
        ("Sensitivity / recall (non-susceptible)", m["recall_sensitivity"],
         "Share of genuinely non-susceptible results the model catches."),
        ("Specificity", m["specificity"],
         "Share of susceptible results correctly left alone."),
        ("Precision (PPV)", m["precision_ppv"],
         "When it says non-susceptible, how often it is right."),
        ("NPV", m["npv"], "When it says susceptible, how often it is right."),
        ("F1", m["f1"], "Harmonic mean of precision and recall."),
        ("Macro F1", m["macro_f1"], "Unweighted mean across both classes."),
        ("Weighted F1", m["weighted_f1"], "Prevalence-weighted."),
        ("Accuracy", m["accuracy"],
         f"Predicting 'susceptible' for everything would score "
         f"{1 - m['positive_rate']:.4f}, which is why accuracy is reported "
         "but never used for selection."),
        ("Brier score", m["brier"],
         "Calibration. Lower is better; matters because the application ranks "
         "by probability."),
    ]
    for k, v, note in rows:
        L.append(f"| {k} | **{v}** | {note} |")
    L.append("")
    L.append("**Confusion matrix at threshold 0.50**\n")
    L.append("| | Predicted susceptible | Predicted non-susceptible |")
    L.append("|---|--:|--:|")
    L.append(f"| **Actually susceptible** | {n(m['tn'])} | {n(m['fp'])} |")
    L.append(f"| **Actually non-susceptible** | {n(m['fn'])} | {n(m['tp'])} |")
    L.append("")
    ce = ev.get("calibration_effect_on_test", {})
    if ce:
        L.append(f"**Calibration.** Isotonic regression fitted on the "
                 f"validation partition improves the test Brier score from "
                 f"{ce['brier_uncalibrated']} to {ce['brier_calibrated']} while "
                 f"leaving ranking essentially unchanged "
                 f"(PR-AUC {ce['pr_auc_uncalibrated']} → "
                 f"{ce['pr_auc_calibrated']}). {ce['note']}\n")
    L.append("![ROC, PR and calibration](../06_MODEL_EVALUATION/figures/01_roc_pr_calibration.png)\n")
    L.append("![Confusion matrix](../06_MODEL_EVALUATION/figures/02_confusion_matrix.png)\n")

    # ---- 6. threshold ------------------------------------------------------
    L.append("## 6. Threshold analysis\n")
    ta = ev["threshold_analysis"]
    L.append(f"The deployed threshold is **{ta['default_threshold']}**, but the "
             "choice is clinical rather than statistical, so alternatives are "
             "published:\n")
    L.append(f"- Maximum F1 at threshold **{ta['best_f1_threshold']}** "
             f"(F1 = {ta['best_f1']:.4f}).")
    L.append(f"- If a missed non-susceptibility is judged three times as costly "
             f"as a false alarm, the optimum moves to "
             f"**{ta['best_threshold_if_fn_costs_3x_fp']}**, giving recall "
             f"{ta['recall_at_that_threshold']:.4f} and specificity "
             f"{ta['specificity_at_that_threshold']:.4f}.")
    L.append(f"\n> {ta['note']}\n")
    L.append("![Threshold analysis](../06_MODEL_EVALUATION/figures/03_threshold_analysis.png)\n")

    # ---- 7. per antibiotic -------------------------------------------------
    L.append("## 7. Where the model works, and where it does not\n")
    pa = pd.DataFrame(ev["per_antibiotic"])
    if len(pa):
        pa = pa.sort_values("pr_auc", ascending=False)
        L.append("Per-antibiotic performance on the test partition. Read "
                 "`pr_auc` against `positive_rate`: an agent whose PR-AUC "
                 "barely exceeds its prevalence is one where the model adds "
                 "little over the base rate.\n")
        L.append("| Antibiotic | Test rows | Non-susceptible rate | PR-AUC | ROC-AUC | Sensitivity | Specificity |")
        L.append("|---|--:|--:|--:|--:|--:|--:|")
        for _, r in pa.iterrows():
            L.append(f"| {r['antibiotic']} | {n(int(r['n']))} | "
                     f"{pct(r['positive_rate'])} | {r['pr_auc']:.4f} | "
                     f"{r['roc_auc']:.4f} | {r['recall_sensitivity']:.4f} | "
                     f"{r['specificity']:.4f} |")
        L.append("")
        weak = pa[pa["pr_auc"] < pa["positive_rate"] * 1.5]
        if len(weak):
            L.append(f"**{len(weak)} agents where the model adds little**: "
                     + ", ".join(f"`{r['antibiotic']}`" for _, r in weak.iterrows())
                     + ". These are typically agents with either very low or "
                     "very high resistance prevalence, where there is little "
                     "variance to explain.\n")
    L.append("![Per-antibiotic PR-AUC](../06_MODEL_EVALUATION/figures/04_per_antibiotic_pr_auc.png)\n")

    po = pd.DataFrame(ev["per_organism"])
    if len(po):
        L.append("### By organism\n")
        L.append("| Organism | Test rows | Non-susceptible rate | PR-AUC | ROC-AUC |")
        L.append("|---|--:|--:|--:|--:|")
        for _, r in po.sort_values("n", ascending=False).head(20).iterrows():
            L.append(f"| {r['organism_clean']} | {n(int(r['n']))} | "
                     f"{pct(r['positive_rate'])} | {r['pr_auc']:.4f} | "
                     f"{r['roc_auc']:.4f} |")
        L.append("")

    # ---- 8. subgroups ------------------------------------------------------
    L.append("## 8. Subgroup performance\n")
    for col, recs in ev.get("subgroups", {}).items():
        d = pd.DataFrame(recs)
        spread = d["pr_auc"].max() - d["pr_auc"].min()
        L.append(f"### By `{col}` (PR-AUC spread {spread:.4f})\n")
        L.append("| Group | Rows | Non-susceptible rate | PR-AUC | ROC-AUC | Sensitivity | Specificity |")
        L.append("|---|--:|--:|--:|--:|--:|--:|")
        for _, r in d.iterrows():
            L.append(f"| {r[col]} | {n(int(r['n']))} | {pct(r['positive_rate'])} | "
                     f"{r['pr_auc']:.4f} | {r['roc_auc']:.4f} | "
                     f"{r['recall_sensitivity']:.4f} | {r['specificity']:.4f} |")
        L.append("")
    L.append("PR-AUC is not directly comparable across groups with different "
             "prevalence, so each group's PR-AUC should be read against its own "
             "non-susceptible rate. ROC-AUC is prevalence-independent and is "
             "the fairer cross-group comparison.\n")

    # ---- 9. temporal -------------------------------------------------------
    L.append("## 9. Temporal generalisation\n")
    tm = ev["temporal_metrics"]
    tv = ev["temporal_vs_grouped"]
    tp = ev["temporal_split"]["partitions"]
    L.append(f"Trained on cultures up to {tp['train']['date_max'][:10]} and "
             f"tested on {n(tp['test']['n_rows'])} rows from "
             f"{tp['test']['date_min'][:10]} onwards, with patients spanning "
             "the cut-off removed from the test side.\n")
    L.append("| | Patient-grouped split | Temporal split | Difference |")
    L.append("|---|--:|--:|--:|")
    L.append(f"| PR-AUC | {m['pr_auc']:.4f} | {tm['pr_auc']:.4f} | "
             f"{tm['pr_auc'] - m['pr_auc']:+.4f} |")
    L.append(f"| ROC-AUC | {m['roc_auc']:.4f} | {tm['roc_auc']:.4f} | "
             f"{tm['roc_auc'] - m['roc_auc']:+.4f} |")
    L.append(f"| Sensitivity | {m['recall_sensitivity']:.4f} | "
             f"{tm['recall_sensitivity']:.4f} | "
             f"{tm['recall_sensitivity'] - m['recall_sensitivity']:+.4f} |")
    L.append(f"| Brier | {m['brier']:.4f} | {tm['brier']:.4f} | "
             f"{tm['brier'] - m['brier']:+.4f} |")
    L.append(f"\n> {tv['interpretation']}\n")

    # ---- 10. three-class ---------------------------------------------------
    L.append("## 10. Secondary 3-class model\n")
    tc = ev["three_class"]
    cr = tc["classification_report"]
    L.append(f"Accuracy {tc['accuracy']:.4f}, macro F1 {tc['macro_f1']:.4f}, "
             f"weighted F1 {tc['weighted_f1']:.4f} "
             f"({n(tc['n_train_rows'])} training rows).\n")
    L.append("| Class | Precision | Recall | F1 | Support |")
    L.append("|---|--:|--:|--:|--:|")
    for cls in ("Susceptible", "Intermediate", "Resistant"):
        if cls in cr:
            r = cr[cls]
            L.append(f"| {cls} | {r['precision']:.4f} | {r['recall']:.4f} | "
                     f"{r['f1-score']:.4f} | {n(int(r['support']))} |")
    L.append(f"\n> {tc['conclusion']}\n")
    L.append("![3-class confusion](../06_MODEL_EVALUATION/figures/05_three_class_confusion.png)\n")

    # ---- 11. architecture --------------------------------------------------
    ac = ev.get("architecture_comparison")
    if ac:
        L.append("## 11. Architecture comparison — one unified model vs one per antibiotic\n")
        L.append(f"`docs/ML_PROBLEM_DEFINITION.md` argued for a single unified "
                 f"model with the antibiotic as a feature. Here is the test. "
                 f"For each of the {ac['n_agents_compared']} highest-volume "
                 "agents, a dedicated single-agent model was trained on that "
                 "agent's rows only and compared with the unified model's "
                 "predictions on the identical test rows.\n")
        L.append("| Antibiotic | Train rows | Test rows | Non-susc. rate | Per-agent PR-AUC | Unified PR-AUC | Unified advantage |")
        L.append("|---|--:|--:|--:|--:|--:|--:|")
        for r in ac["per_agent"]:
            L.append(f"| {r['antibiotic']} | {n(r['n_train'])} | "
                     f"{n(r['n_test'])} | {pct(r['positive_rate'])} | "
                     f"{r['per_antibiotic_model_pr_auc']:.4f} | "
                     f"{r['unified_model_pr_auc']:.4f} | "
                     f"{r['unified_advantage']:+.4f} |")
        adv = ac["mean_unified_advantage_pr_auc"]
        wins = ac["n_agents_where_unified_wins"]
        total = ac["n_agents_compared"]
        L.append(f"\n**Result: the unified model wins on {wins} of {total} "
                 f"agents, mean advantage {adv:+.4f} PR-AUC.**\n")
        if adv < 0:
            L.append("This is the honest answer, and it does not fully favour "
                     "the architecture chosen in "
                     "`docs/ML_PROBLEM_DEFINITION.md`. On the highest-volume "
                     f"agents a dedicated single-agent model is on average "
                     f"{abs(adv):.4f} PR-AUC **better** than the unified model. "
                     "That is what theory predicts: with tens of thousands of "
                     "rows for one agent, a specialised model can fit that "
                     "agent's own interactions without spending capacity on "
                     "fifty-three others.\n")
            L.append("The unified architecture is still the right choice for "
                     "this application, for reasons the table cannot show:\n")
            L.append(f"1. **The margin is small.** {abs(adv):.4f} PR-AUC on the "
                     "agents most favourable to the alternative.")
            L.append("2. **This comparison is restricted to agents with enough "
                     "data to make it possible at all.** It required at least "
                     "20,000 training rows and 2,000 test rows per agent. Most "
                     "of the 54 agents do not clear that bar — Cefpodoxime has "
                     "9 rows in total, Chloramphenicol 12, Meropenem/"
                     "Vaborbactam 26. A dedicated model for those is not "
                     "*worse*; it is untrainable. The unified model still "
                     "scores them by borrowing from their class and the "
                     "organism.")
            L.append("3. **The application needs to score every agent for a new "
                     "isolate**, including agents the laboratory did not test. "
                     "Fifty-four separately-versioned models, most fitted to a "
                     "few hundred rows, is a worse system than one model with "
                     "a shared representation.")
            L.append("4. **Maintenance.** One model to retrain, calibrate, "
                     "explain and monitor rather than 54.\n")
            L.append("The trade-off is therefore stated explicitly rather than "
                     "claimed away: the unified model gives up a small amount "
                     "of accuracy on common agents in exchange for coverage of "
                     "rare ones and a single maintainable artefact. A "
                     "deployment that only ever needed the ten commonest agents "
                     "should reconsider and use per-agent models.\n")
        else:
            L.append("The unified model matches or beats the dedicated models "
                     "even on the agents with the MOST data, where a "
                     "specialised model is at its strongest — and unlike them "
                     "it also covers the long tail (Cefpodoxime has 9 rows, "
                     "Chloramphenicol 12) where a dedicated model cannot be "
                     "trained at all.\n")
        L.append("![Architecture comparison](../06_MODEL_EVALUATION/figures/06_architecture_comparison.png)\n")

    L.append("## 12. Reproducibility\n")
    L.append(f"- Random seed `{cfg['random_seed']}` throughout: splitting, "
             "subsampling, model initialisation and the hyperparameter search.")
    L.append("- Every experiment is logged to "
             "`05_MODEL_TRAINING/experiments/experiment_log.csv`.")
    L.append("- Raw-data integrity is verifiable with "
             "`python scripts/00_verify_raw_integrity.py`.")
    L.append("- The full pipeline is re-runnable end to end with "
             "`python scripts/run_all.py`.\n")
    return "\n".join(L)


