"""Generate documentation from the audit artefacts.

Everything written here is derived from the real profiling output
(02_DATA_ANALYSIS/reports/*.json). Nothing is hand-written or assumed, so the
docs cannot drift away from the data.

Writes:
  docs/DATA_DICTIONARY.md
  01_DATA/DATA_DICTIONARY.md          (same content, folder-local copy)
  docs/diagrams/dataset_relationships.png
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import FancyArrowPatch, FancyBboxPatch  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from config.paths import ANALYSIS_DIR, DATA_DIR, DOCS_DIR, REPORT_DIR  # noqa: E402

REPORTS = ANALYSIS_DIR / "reports"


def fmt(n) -> str:
    return f"{n:,}" if isinstance(n, (int, float)) and not isinstance(n, bool) else str(n)


def data_dictionary(audit: dict) -> str:
    L = []
    L.append("# Data Dictionary\n")
    L.append("> Auto-generated by `scripts/03_generate_data_docs.py` from "
             "`02_DATA_ANALYSIS/reports/dataset_audit.json`.\n")
    L.append("> Every number below was measured on the real files. Missing values "
             "are counted after mapping the literal export tokens "
             "(`Null`, `NULL`, `NaN`, `NA`, empty string) to NA.\n")

    L.append("## 1. File inventory\n")
    L.append("| Dataset | File | Size (MB) | Rows | Columns | Exact duplicate rows | MD5 |")
    L.append("|---|---|---:|---:|---:|---:|---|")
    for d in audit["datasets"]:
        L.append(f"| `{d['key']}` | `{d['file_name']}` | {d['file_size_mb']:,.1f} | "
                 f"{fmt(d['n_rows'])} | {d['n_columns']} | "
                 f"{fmt(d['n_exact_duplicate_rows'])} "
                 f"({d['pct_exact_duplicate_rows']}%) | `{d['md5'][:12]}…` |")
    L.append("")
    L.append(f"**Source directory (read-only, never modified):** "
             f"`{Path(audit['datasets'][0]['file_path']).parent}`\n")

    for d in audit["datasets"]:
        L.append(f"\n---\n\n## Dataset: `{d['key']}` — `{d['file_name']}`\n")
        L.append(f"- **Path:** `{d['file_path']}`")
        L.append(f"- **Size:** {d['file_size_mb']:,.1f} MB "
                 f"({fmt(d['file_size_bytes'])} bytes)")
        L.append(f"- **Rows:** {fmt(d['n_rows'])}")
        L.append(f"- **Columns:** {d['n_columns']}")
        L.append(f"- **Exact duplicate rows:** {fmt(d['n_exact_duplicate_rows'])} "
                 f"({d['pct_exact_duplicate_rows']}%)")
        L.append(f"- **MD5:** `{d['md5']}`")
        it = d.get("identifier_triple")
        if it:
            L.append(f"- **Identifier triple** `{' + '.join(it['columns'])}`: "
                     f"{fmt(it['n_unique_combinations'])} unique combinations, "
                     f"{it['rows_per_combination_mean']} rows each on average, "
                     f"max {fmt(it['max_rows_for_one_combination'])} rows for one "
                     f"combination → "
                     f"{'IS' if it['is_primary_key'] else 'is NOT'} a primary key.")
        L.append("")
        L.append("| # | Column | Type | Missing | % Missing | Unique | Dominant value share | Example values |")
        L.append("|--:|---|---|--:|--:|--:|--:|---|")
        for i, c in enumerate(d["column_profiles"], 1):
            typ = "numeric" if c["is_numeric"] else "categorical / text"
            ex = ", ".join(f"`{v}`" for v in c["sample_values"][:3])
            dom = c.get("dominant_value_share")
            L.append(f"| {i} | `{c['column']}` | {typ} | {fmt(c['n_missing'])} | "
                     f"{c['pct_missing']}% | {fmt(c['n_unique'])} | "
                     f"{dom if dom is not None else '–'} | {ex} |")
        L.append("")

        # numeric summaries
        nums = [c for c in d["column_profiles"] if c["is_numeric"]]
        if nums:
            L.append(f"### Numeric summary — `{d['key']}`\n")
            L.append("| Column | Min | Max | Mean | Std |")
            L.append("|---|--:|--:|--:|--:|")
            for c in nums:
                s = c["numeric_summary"]
                L.append(f"| `{c['column']}` | {s['min']:,.4g} | {s['max']:,.4g} | "
                         f"{s['mean']:,.4g} | {s['std']:,.4g} |")
            L.append("")

        # categorical value counts for genuinely low-cardinality columns
        cats = [c for c in d["column_profiles"] if "value_counts" in c
                and not c["is_numeric"] and len(c["value_counts"]) <= 30]
        if cats:
            L.append(f"### Categorical value distributions — `{d['key']}`\n")
            for c in cats:
                L.append(f"**`{c['column']}`** ({fmt(c['n_unique'])} distinct)\n")
                L.append("| Value | Count | % of non-missing |")
                L.append("|---|--:|--:|")
                tot = sum(c["value_counts"].values())
                for k, v in c["value_counts"].items():
                    L.append(f"| `{k}` | {fmt(v)} | {100*v/tot:.2f}% |")
                L.append("")

        # high-cardinality: show top values only
        tops = [c for c in d["column_profiles"] if "top_values" in c]
        if tops:
            L.append(f"### High-cardinality columns — most frequent values — `{d['key']}`\n")
            for c in tops:
                L.append(f"**`{c['column']}`** ({fmt(c['n_unique'])} distinct) — top 15\n")
                L.append("| Value | Count |")
                L.append("|---|--:|")
                for k, v in c["top_values"].items():
                    L.append(f"| `{k}` | {fmt(v)} |")
                L.append("")
    return "\n".join(L)


def relationship_diagram(rel: dict, out_png: Path) -> None:
    """Entity-relationship diagram drawn from the measured cardinalities."""
    grains = {g["table"]: g for g in rel["grains"]}
    rels = {(r["left"], r["right"]): r for r in rel["relationships"]}
    ps = rel["patient_structure"]

    boxes = {
        "cohort":       (0.50, 0.50, "#2563eb"),
        "demographics": (0.13, 0.83, "#0891b2"),
        "labs":         (0.13, 0.17, "#0891b2"),
        "resistance":   (0.87, 0.83, "#c2410c"),
        "prior_med":    (0.87, 0.17, "#c2410c"),
    }
    titles = {
        "cohort": "microbiology_cultures_cohort\n(LABEL TABLE)",
        "demographics": "microbiology_cultures_demographics",
        "labs": "microbiology_cultures_labs",
        "resistance": "microbiology_cultures_\nmicrobial_resistance",
        "prior_med": "microbiology_cultures_prior_med",
    }
    grain_txt = {
        "cohort": "grain: order x organism x antibiotic",
        "demographics": "grain: culture order",
        "labs": "grain: order x Period_Day",
        "resistance": "grain: prior resistant event",
        "prior_med": "grain: prior medication admin",
    }

    fig, ax = plt.subplots(figsize=(16, 10))
    ax.set_xlim(-0.03, 1.03); ax.set_ylim(-0.10, 1.10); ax.axis("off")

    W, H = 0.29, 0.135
    coords = {}
    for name, (x, y, color) in boxes.items():
        box = FancyBboxPatch((x - W / 2, y - H / 2), W, H,
                             boxstyle="round,pad=0.010,rounding_size=0.018",
                             linewidth=2.2, edgecolor=color,
                             facecolor=color + "18", zorder=3)
        ax.add_patch(box)
        n = grains[name]["n_rows"]
        ax.text(x, y + 0.038, titles[name], ha="center", va="center",
                fontsize=10.5, fontweight="bold", color=color, zorder=4)
        ax.text(x, y - 0.008, f"{n:,} rows", ha="center", va="center",
                fontsize=9.5, zorder=4)
        ax.text(x, y - 0.042, grain_txt[name], ha="center", va="center",
                fontsize=8, style="italic", color="#444", zorder=4)
        coords[name] = (x, y)

    def edge_point(cx, cy, tx, ty, pad=0.012):
        """Where the line (cx,cy)->(tx,ty) leaves the box centred at (cx,cy)."""
        dx, dy = tx - cx, ty - cy
        if dx == 0 and dy == 0:
            return cx, cy
        sx = (W / 2 + pad) / abs(dx) if dx else float("inf")
        sy = (H / 2 + pad) / abs(dy) if dy else float("inf")
        s = min(sx, sy)
        return cx + dx * s, cy + dy * s

    def arrow(a, b, label):
        xa, ya = coords[a]
        xb, yb = coords[b]
        p0 = edge_point(xa, ya, xb, yb)
        p1 = edge_point(xb, yb, xa, ya)
        ax.add_patch(FancyArrowPatch(
            p0, p1, arrowstyle="-|>", mutation_scale=17,
            linewidth=1.5, color="#666", zorder=2))
        # Label sits 55% of the way along the connector, biased outward so it
        # never sits on top of the central cohort box.
        lx = p0[0] + 0.55 * (p1[0] - p0[0])
        ly = p0[1] + 0.55 * (p1[1] - p0[1])
        ax.text(lx, ly, label, ha="center", va="center", fontsize=8.2,
                color="#111", zorder=5, linespacing=1.45,
                bbox=dict(boxstyle="round,pad=0.34", fc="white", ec="#bbb",
                          lw=0.8, alpha=0.97))

    for other in ("demographics", "labs", "resistance", "prior_med"):
        r = rels[("cohort", other)]
        arrow("cohort", other,
              f"order_proc_id_coded\n{r['cardinality']}\n"
              f"{r['pct_left_keys_matched']:.1f}% of cohort orders matched")

    ax.text(0.5, 1.075,
            "Dataset relationships — measured, not assumed", ha="center",
            fontsize=16, fontweight="bold")
    ax.text(0.5, 1.020,
            f"{ps['n_patients']:,} patients   |   {ps['n_encounters']:,} encounters"
            f"   |   {ps['n_culture_orders']:,} culture orders"
            f"   |   {ps['n_rows_cohort']:,} organism-antibiotic label rows",
            ha="center", fontsize=10.5, color="#333")
    ax.text(0.5, -0.055,
            "Join key hierarchy: anon_id (patient)  >  pat_enc_csn_id_coded "
            "(encounter)  >  order_proc_id_coded (culture order).\n"
            "order_proc_id_coded alone is unique per culture order and is the "
            "single join key used by the pipeline. Every join is validated for "
            "key uniqueness and row count before it is executed.",
            ha="center", va="center", fontsize=9.2, color="#333",
            bbox=dict(boxstyle="round,pad=0.55", fc="#f6f7f9", ec="#ccc"))

    out_png.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_png, dpi=170, bbox_inches="tight", facecolor="white")
    plt.close(fig)


def main() -> None:
    audit = json.loads((REPORTS / "dataset_audit.json").read_text(encoding="utf-8"))
    md = data_dictionary(audit)
    for p in (DOCS_DIR / "DATA_DICTIONARY.md", DATA_DIR / "DATA_DICTIONARY.md"):
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(md, encoding="utf-8")
        print("wrote", p)

    rel_path = REPORTS / "relationships.json"
    if rel_path.exists():
        rel = json.loads(rel_path.read_text(encoding="utf-8"))
        for out in (DOCS_DIR / "diagrams" / "dataset_relationships.png",
                    REPORT_DIR / "diagrams" / "dataset_relationships.png"):
            relationship_diagram(rel, out)
            print("wrote", out)


if __name__ == "__main__":
    main()
